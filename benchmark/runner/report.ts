import type { RunScore } from "./score";

const pct = (v: number | null) => (v === null ? "n/a" : `${Math.round(v * 100)}%`);
const num = (v: number | null) => (v === null ? "n/a" : String(Math.round(v * 10) / 10));
const secs = (v: number | null) => (v === null ? "n/a" : `${(v / 1000).toFixed(1)} s`);

const ROWS: [string, string, (s: RunScore) => string][] = [
  ["Precision (correct / posted)", "≥ 60%", (s) => pct(s.precision)],
  ["Seeded-bug recall", "report", (s) => pct(s.recall)],
  ["Inline comments per PR (median)", "≤ 7", (s) => num(s.inlinePerPr)],
  ["Comments off the diff", "0", (s) => num(s.offDiff)],
  ["Duplicate comments", "0", (s) => num(s.duplicates)],
  ["Comments on clean refactors", "~0", (s) => num(s.cleanComments)],
  ["Re-posts on an unchanged re-push", "0", (s) => num(s.rerunPosted)],
  ["LLM calls on an unchanged layer", "0", (s) => num(s.rerunLlmCalls)],
  ["Review latency (median)", "≤ 90 s", (s) => secs(s.latencyMs)],
];

/** benchmark/results.md: the PRD §6 table, one column per reviewer, plus the method note. */
export function renderResults(opts: {
  repo: string;
  prs: number;
  runs: number;
  model: string;
  at: Date;
  scores: Record<string, RunScore>;
}): string {
  const names = Object.keys(opts.scores);
  const header = `| Metric | Target | ${names.join(" | ")} |`;
  const rule = `|---|---|${names.map(() => "---|").join("")}`;
  const rows = ROWS.map(
    ([label, target, cell]) =>
      `| ${label} | ${target} | ${names.map((n) => cell(opts.scores[n] as RunScore)).join(" | ")} |`,
  );
  return [
    "# Benchmark results",
    "",
    `Generated by \`pnpm bench\` on ${opts.at.toISOString().slice(0, 10)}: ${opts.prs} labelled PRs on \`${opts.repo}\`, ${opts.runs} runs per reviewer, medians. Model: \`${opts.model}\`.`,
    "",
    header,
    rule,
    ...rows,
    "",
    "## Method",
    "",
    "- `benchmark/labels.json` (seeded bugs and other acceptable spots per PR) was committed before any run.",
    "- A comment is correct when it lands within 3 lines of a labelled spot in the same file.",
    "- Recall counts every seeded bug a reviewer reported anywhere (inline or summary).",
    "- **naive** uses the same model, prompt and code context as Sift, one call per file, and posts every finding. No grounding, judge, ranking, budget or dedupe. The difference between the columns is the pipeline.",
    "- Re-push rows run each stack PR twice with nothing changed, the second time seeing the first run's comments.",
    "- Nothing is posted to GitHub: the runner reads real PR data and captures what each reviewer would post.",
    "",
  ].join("\n");
}
